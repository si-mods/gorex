package rexproto

import (
	"bytes"
	_ "embed"
	"encoding/json"
	"fmt"
	"go/format"
)

//go:embed protocol.json
var protocolJSON []byte

type spec struct {
	APIRevision      int               `json:"api_revision"`
	APIMinRevision   int               `json:"api_min_revision"`
	UploadRevision   int               `json:"upload_revision"`
	DownloadRevision int               `json:"download_revision"`
	TunnelRevision   int               `json:"tunnel_revision"`
	ControlProtocol  string            `json:"control_protocol"`
	TerminalProtocol string            `json:"terminal_protocol"`
	BytesProtocol    string            `json:"bytes_protocol"`
	DataWelcomeByte  byte              `json:"data_welcome_byte"`
	DataRejectByte   byte              `json:"data_reject_byte"`
	MaxChunk         int               `json:"max_chunk"`
	Methods          map[string]string `json:"methods"`
	Creators         map[string]string `json:"creators"`
}

func loadSpec() (spec, error) {
	var s spec
	if err := json.Unmarshal(protocolJSON, &s); err != nil {
		return spec{}, err
	}
	return s, nil
}

func renderGo(s spec) ([]byte, error) {
	var buf bytes.Buffer
	buf.WriteString("// Code generated by internal/rexproto/gen.go from protocol.json; DO NOT EDIT.\n\n")
	buf.WriteString("package rexproto\n\n")
	buf.WriteString("//go:generate go run gen.go\n\n")
	fmt.Fprintf(&buf, "const (\n")
	fmt.Fprintf(&buf, "\tAPIRevision = %d\n", s.APIRevision)
	fmt.Fprintf(&buf, "\tAPIMinRevision = %d\n", s.APIMinRevision)
	fmt.Fprintf(&buf, "\tUploadRevision = %d\n", s.UploadRevision)
	fmt.Fprintf(&buf, "\tDownloadRevision = %d\n", s.DownloadRevision)
	fmt.Fprintf(&buf, "\tTunnelRevision = %d\n", s.TunnelRevision)
	fmt.Fprintf(&buf, "\tControlProtocol = %q\n", s.ControlProtocol)
	fmt.Fprintf(&buf, "\tTerminalProtocol = %q\n", s.TerminalProtocol)
	fmt.Fprintf(&buf, "\tBytesProtocol = %q\n", s.BytesProtocol)
	fmt.Fprintf(&buf, "\tDataWelcomeByte byte = 0x%02x\n", s.DataWelcomeByte)
	fmt.Fprintf(&buf, "\tDataRejectByte byte = 0x%02x\n", s.DataRejectByte)
	fmt.Fprintf(&buf, "\tMaxChunk = %d\n", s.MaxChunk)
	fmt.Fprintf(&buf, "\tMethodTerminalUploadBegin = %q\n", s.Methods["terminal_upload_begin"])
	fmt.Fprintf(&buf, "\tMethodTerminalDownloadBegin = %q\n", s.Methods["terminal_download_begin"])
	fmt.Fprintf(&buf, "\tMethodTunnelInfo = %q\n", s.Methods["tunnel_info"])
	fmt.Fprintf(&buf, "\tCreatorTerminal = %q\n", s.Creators["terminal"])
	fmt.Fprintf(&buf, "\tCreatorTunnel = %q\n", s.Creators["tunnel"])
	fmt.Fprintf(&buf, ")\n")
	return format.Source(buf.Bytes())
}

func renderTS(s spec) []byte {
	var buf bytes.Buffer
	buf.WriteString("// Code generated by internal/rexproto/gen.go from protocol.json; DO NOT EDIT.\n\n")
	buf.WriteString("export const RexProtocol = {\n")
	fmt.Fprintf(&buf, "  apiRevision: %d,\n", s.APIRevision)
	fmt.Fprintf(&buf, "  apiMinRevision: %d,\n", s.APIMinRevision)
	fmt.Fprintf(&buf, "  uploadRevision: %d,\n", s.UploadRevision)
	fmt.Fprintf(&buf, "  downloadRevision: %d,\n", s.DownloadRevision)
	fmt.Fprintf(&buf, "  tunnelRevision: %d,\n", s.TunnelRevision)
	fmt.Fprintf(&buf, "  controlProtocol: %q,\n", s.ControlProtocol)
	fmt.Fprintf(&buf, "  terminalProtocol: %q,\n", s.TerminalProtocol)
	fmt.Fprintf(&buf, "  bytesProtocol: %q,\n", s.BytesProtocol)
	fmt.Fprintf(&buf, "  dataWelcomeByte: 0x%02x,\n", s.DataWelcomeByte)
	fmt.Fprintf(&buf, "  dataRejectByte: 0x%02x,\n", s.DataRejectByte)
	fmt.Fprintf(&buf, "  maxChunk: %d,\n", s.MaxChunk)
	buf.WriteString("} as const;\n")
	return buf.Bytes()
}

func renderSwift(s spec) []byte {
	var buf bytes.Buffer
	buf.WriteString("// Code generated by internal/rexproto/gen.go from protocol.json; DO NOT EDIT.\n\n")
	buf.WriteString("enum RexProtocol {\n")
	fmt.Fprintf(&buf, "    static let apiRevision = %d\n", s.APIRevision)
	fmt.Fprintf(&buf, "    static let apiMinRevision = %d\n", s.APIMinRevision)
	fmt.Fprintf(&buf, "    static let uploadRevision = %d\n", s.UploadRevision)
	fmt.Fprintf(&buf, "    static let downloadRevision = %d\n", s.DownloadRevision)
	fmt.Fprintf(&buf, "    static let tunnelRevision = %d\n", s.TunnelRevision)
	fmt.Fprintf(&buf, "    static let controlProtocol = %q\n", s.ControlProtocol)
	fmt.Fprintf(&buf, "    static let terminalProtocol = %q\n", s.TerminalProtocol)
	fmt.Fprintf(&buf, "    static let bytesProtocol = %q\n", s.BytesProtocol)
	fmt.Fprintf(&buf, "    static let dataWelcomeByte: UInt8 = 0x%02x\n", s.DataWelcomeByte)
	fmt.Fprintf(&buf, "    static let dataRejectByte: UInt8 = 0x%02x\n", s.DataRejectByte)
	fmt.Fprintf(&buf, "    static let maxChunk = %d\n", s.MaxChunk)
	fmt.Fprintf(&buf, "    static let methodTerminalUploadBegin = %q\n", s.Methods["terminal_upload_begin"])
	fmt.Fprintf(&buf, "    static let methodTerminalDownloadBegin = %q\n", s.Methods["terminal_download_begin"])
	fmt.Fprintf(&buf, "    static let methodTunnelInfo = %q\n", s.Methods["tunnel_info"])
	buf.WriteString("}\n")
	return buf.Bytes()
}

// GenerateAll renders all generated protocol files keyed by repo-relative path.
func GenerateAll() (map[string][]byte, error) {
	s, err := loadSpec()
	if err != nil {
		return nil, err
	}
	goSrc, err := renderGo(s)
	if err != nil {
		return nil, err
	}
	return map[string][]byte{
		"internal/rexproto/protocol.gen.go":   goSrc,
		"web/src/rex-protocol.gen.ts":         renderTS(s),
		"ios/GoRex/Rex/RexProtocol.gen.swift": renderSwift(s),
	}, nil
}
