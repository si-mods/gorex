// ShownText strips terminal escape sequences (CSI, OSC, DCS, SOS, PM, APC, and
// bare ESC), C0/C1 controls except tab and LF, bidi controls, zero-width
// characters, private-use glyphs, noncharacters, and U+FFFD, and appends U+FE0E
// behind text-default emoji characters (matching ios/Shared/ShownText.swift).
func ShownText(s string) string {
	plainASCII := true
	for i := 0; i < len(s); i++ {
		b := s[i]
		if b >= 0x80 || !(b == 0x09 || b == 0x0A || (b >= 0x20 && b < 0x7F)) {
			plainASCII = false
			break
		}
	}
	if plainASCII {
		return s
	}

	rs := []rune(s)
	var out strings.Builder
	out.Grow(len(s))
	for i := 0; i < len(rs); {
		v := rs[i]
		if shownStarts(v) {
			i = shownEnd(rs, i)
			continue
		}
		if shownKeeps(v) {
			out.WriteRune(v)
			if shownTextStyled(rs, i) {
				out.WriteRune('\uFE0E')
			}
		}
		i++
	}
	return out.String()
}

func shownKeeps(v rune) bool {
	switch {
	case v == 0x09 || v == 0x0A:
		return true
	case v >= 0 && v <= 0x1F, v == 0x7F, v >= 0x80 && v <= 0x9F:
		return false
	case v == 0x061C, v == 0x180E, v == 0x200B, v == 0x200E, v == 0x200F,
		v >= 0x202A && v <= 0x202E,
		v >= 0x2060 && v <= 0x2064,
		v >= 0x2066 && v <= 0x206F,
		v == 0xFEFF:
		return false
	case v >= 0xE000 && v <= 0xF8FF,
		v >= 0xF0000 && v <= 0xFFFFD,
		v >= 0x100000 && v <= 0x10FFFD:
		return false
	case v >= 0xFDD0 && v <= 0xFDEF, v == 0xFFFD:
		return false
	default:
		return (uint32(v) & 0xFFFE) != 0xFFFE
	}
}

func shownTextStyled(s []rune, i int) bool {
	v := s[i]
	if v <= 0x7F || !isTextDefaultEmoji(v) {
		return false
	}
	if i > 0 && s[i-1] == 0x200D {
		return false
	}
	if i+1 >= len(s) {
		return true
	}
	next := s[i+1]
	switch {
	case next == 0xFE0E, next == 0xFE0F, next == 0x200D, next == 0x20E3,
		next >= 0x1F3FB && next <= 0x1F3FF:
		return false
	default:
		return true
	}
}

func shownStarts(v rune) bool {
	return v == 0x1B || v == 0x9B || v == 0x9D || v == 0x90 || v == 0x98 || v == 0x9E || v == 0x9F
}

func shownEnd(s []rune, start int) int {
	v := s[start]
	i := start + 1
	switch v {
	case 0x9B:
		return shownCSI(s, i)
	case 0x9D, 0x90, 0x98, 0x9E, 0x9F:
		return shownSeqText(s, i)
	default:
		if i >= len(s) {
			return i
		}
		switch {
		case s[i] == 0x5B:
			return shownCSI(s, i+1)
		case s[i] == 0x5D || s[i] == 0x50 || s[i] == 0x58 || s[i] == 0x5E || s[i] == 0x5F:
			return shownSeqText(s, i+1)
		case s[i] >= 0x30 && s[i] <= 0x7E:
			return i + 1
		default:
			if shownStarts(s[i]) {
				return i
			}
			j := i
			for j < len(s) && s[j] >= 0x20 && s[j] <= 0x2F {
				j++
			}
			return min(j+1, len(s))
		}
	}
}

func shownCSI(s []rune, start int) int {
	i := start
	for i < len(s) && !(s[i] >= 0x40 && s[i] <= 0x7E) {
		i++
	}
	return min(i+1, len(s))
}

func shownSeqText(s []rune, start int) int {
	for i := start; i < len(s); i++ {
		if s[i] == 0x07 || s[i] == 0x9C {
			return i + 1
		}
		if s[i] == 0x1B && i+1 < len(s) && s[i+1] == 0x5C {
			return i + 2
		}
	}
	return len(s)
}

