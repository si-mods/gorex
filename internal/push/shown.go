func isTextDefaultEmoji(r rune) bool {
	idx := sort.Search(len(textDefaultEmojiRanges), func(i int) bool {
		return textDefaultEmojiRanges[i][1] >= r
	})
	return idx < len(textDefaultEmojiRanges) && textDefaultEmojiRanges[idx][0] <= r
}
